/**
  * @brief  UART receive callback
  * @param  huart: UART handle
  * @retval None
  */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if(huart->Instance == USART1)
  {
    // Echo back received data
    printf("Received: %c (0x%02X)\r\n", rx_data, rx_data);

    // Process commands
    switch(rx_data)
    {
      case 'L':
      case 'l':
        HAL_GPIO_TogglePin(BLed_GPIO_Port, BLed_Pin);
        printf("LED Toggled\r\n");
        break;

      case 'V':
      case 'v':
        printf("App Version: %d.%d\r\n", APP_Version[0], APP_Version[1]);
        break;

      case 'S':
      case 's':
        printf("Status: Running OK\r\n");
        printf("Counter: %lu\r\n", led_toggle_counter);
        break;

      default:
        printf("Unknown command\r\n");
        break;
    }

    // Re-enable reception
    HAL_UART_Receive_IT(&huart1, &rx_data, 1);
  }
}

